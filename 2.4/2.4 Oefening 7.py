# -- Variabelen --
F = float(input("Geef de temperatuur in: ")) # Vraagt de temperatuur in Fahrenheit
C = (F - 32) * 5/9 # Zet de temperatuur om van Fahrenheit naar Celsius

# -- Functies --
print(f"{F}°F is gelijk aan {C:.1f}°C") # Print aan hoeveel Celsius de opgegeven hoeveelheid Fahrenheit gelijk is